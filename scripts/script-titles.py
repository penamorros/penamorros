# Real calligraphy, set once and kept as outlines: the titles are shaped with HarfBuzz from Pinyon Script (ligatures and joins as the
# designer drew them; the capitals C and V from Italianno, see script-hybrid.py), then written out glyph by glyph as SVG paths into
# src/scriptTitles.ts. The page loads no font: the words are drawn, and each glyph can be written in by the pen in turn.
#   python3 scripts/script-titles.py <Pinyon Script .ttf> <Italianno .ttf>
import sys, os, json
sys.path.insert(0, os.path.dirname(__file__))
from importlib import import_module
hy = import_module('script-hybrid')
base, alt = hy.load(sys.argv[1]), hy.load(sys.argv[2])
WORDS = {'title': ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'My Story', 'Core Values', 'My Skills', 'Resume', 'Projects', 'Article Mentions', 'Contact Card'], 'hero': ['Manuel', 'Peña-Morros']}
out = {}
for kind, words in WORDS.items():
    for w in words:
        out[w] = dict(hy.word(base, w), k=kind)  # all Pinyon Script, as everywhere on the site
src = '// generated by scripts/script-titles.py: the titles in real calligraphy (Pinyon Script), as outlines\n'
src += '// x, y, w, h: the ink box in units of 1/100 em (baseline at y = 0); g: one path per glyph, in writing order\n'
src += 'export const SCRIPT: Record<string, { x: number; y: number; w: number; h: number; g: string[]; k: string }> = ' + json.dumps(out) + '\n'
open('src/scriptTitles.ts', 'w').write(src)
print({k: (v['w'], v['h'], len(v['g'])) for k, v in out.items()}, len(src) // 1024, 'KB')
